#: 英字は語として一致させる (部分一致だと無関係な語に当たる)
_ASCII_FOOD = ("food", "foodie", "foodporn", "seafood", "mukbang", "asmreating",
               "cafe", "brunch", "bakery", "boba", "dessert", "recipe",
               "cooking", "snack", "ramen", "sushi")
_ASCII_RE = re.compile(r"(?<![a-z0-9])(" + "|".join(_ASCII_FOOD) + r")(?![a-z0-9])")


def _hay(texts: Iterable[str | None]) -> str:
    return " ".join(str(t) for t in texts if t).lower()


def looks_like_goods(*texts: str | None) -> bool:
    """食にまつわる語を含むが「物」であると分かるか (食器・炊飯器など)."""
    hay = _hay(texts)
    return any(w in hay for w in GOODS_WORDS)


def is_food(*texts: str | None) -> bool:
    """食べ物・飲み物の話か.

    ``texts`` にはキャプション・ハッシュタグ・商品名などを渡す。
    「物」と分かる語が入っていれば、食べ物語があっても物として扱う。
    """
    hay = _hay(texts)
    if not hay:
        return False
    if looks_like_goods(hay):
        return False
    if any(w in hay for w in FOOD_WORDS):
        return True
    return bool(_ASCII_RE.search(hay))
